-- Ephemeral Supabase CLI database only. Mirrors the existing BVOM table and
-- authenticated-owner RLS; this file is NOT a production migration.
CREATE TABLE public.bvom_cloud_state (
  user_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  revision bigint NOT NULL DEFAULT 1 CHECK (revision > 0),
  data_version text NOT NULL DEFAULT '1',
  state jsonb NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.bvom_cloud_state ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE ON public.bvom_cloud_state TO authenticated;

CREATE POLICY bvom_cloud_state_select_own ON public.bvom_cloud_state
  FOR SELECT TO authenticated USING ((SELECT auth.uid()) = user_id);
CREATE POLICY bvom_cloud_state_insert_own ON public.bvom_cloud_state
  FOR INSERT TO authenticated WITH CHECK ((SELECT auth.uid()) = user_id);
CREATE POLICY bvom_cloud_state_update_own ON public.bvom_cloud_state
  FOR UPDATE TO authenticated
  USING ((SELECT auth.uid()) = user_id)
  WITH CHECK ((SELECT auth.uid()) = user_id);

-- The actual BVOM signed-in account lifecycle also reads its legacy cloud
-- document and confirms entitlement. Mirror those EXISTING interfaces only in
-- this disposable database, so the browser proof needs no fake account state.
CREATE TABLE public.bvom_data (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  data jsonb NOT NULL
);
ALTER TABLE public.bvom_data ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE ON public.bvom_data TO authenticated;
CREATE POLICY bvom_data_select_own ON public.bvom_data FOR SELECT
  TO authenticated USING ((SELECT auth.uid()) = user_id);
CREATE POLICY bvom_data_insert_own ON public.bvom_data FOR INSERT
  TO authenticated WITH CHECK ((SELECT auth.uid()) = user_id);
CREATE POLICY bvom_data_update_own ON public.bvom_data FOR UPDATE
  TO authenticated USING ((SELECT auth.uid()) = user_id)
  WITH CHECK ((SELECT auth.uid()) = user_id);

CREATE FUNCTION public.ensure_bvom_entitlement() RETURNS jsonb
  LANGUAGE sql STABLE SECURITY INVOKER AS $$
  SELECT jsonb_build_object('user_id', auth.uid(), 'status', 'complimentary')
  WHERE auth.uid() IS NOT NULL;
$$;
REVOKE ALL ON FUNCTION public.ensure_bvom_entitlement() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.ensure_bvom_entitlement() TO authenticated;
